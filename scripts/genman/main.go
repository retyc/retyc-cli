// Command genman writes the manual pages of retyc, one per command, from the
// cobra command tree. scripts/manpages.sh runs it for the Linux packages.
//
// cobra/doc renders the help texts as Markdown (go-md2man). They are plain
// text, so they are escaped first, here only: `retyc --help` is untouched.
//
// Usage: genman <output-dir> <version> <date YYYY-MM-DD>
package main

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"

	"github.com/spf13/cobra"
	"github.com/spf13/cobra/doc"
	"github.com/spf13/pflag"

	"github.com/retyc/retyc-cli/cmd"
)

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "genman:", err)
		os.Exit(1)
	}
}

func run(args []string) error {
	if len(args) != 3 {
		return errors.New("usage: genman <output-dir> <version> <date YYYY-MM-DD>")
	}

	dir, version := args[0], args[1]

	// A fixed date (the commit's) keeps the pages reproducible.
	date, err := time.Parse(time.DateOnly, args[2])
	if err != nil {
		return fmt.Errorf("date: %w", err)
	}

	root := cmd.Root()
	// cobra adds `completion` only when the command runs; the pages list it.
	root.InitDefaultCompletionCmd()
	// No "Auto generated by spf13/cobra on <today>" section.
	root.DisableAutoGenTag = true

	header := &doc.GenManHeader{
		Section: "1",
		Date:    &date,
		Source:  "retyc " + version,
		Manual:  "Retyc Manual",
	}

	escapeTree(root, map[*pflag.Flag]bool{})

	return genTree(root, header, dir)
}

// genTree writes one page per available command, as doc.GenManTree does,
// with the option lists fixed by fixOptions.
func genTree(c *cobra.Command, header *doc.GenManHeader, dir string) error {
	for _, sub := range c.Commands() {
		if !sub.IsAvailableCommand() || sub.IsAdditionalHelpTopicCommand() {
			continue
		}

		if err := genTree(sub, header, dir); err != nil {
			return err
		}
	}

	// GenMan fills the title from the command: each page needs its own copy.
	h := *header

	var buf bytes.Buffer
	if err := doc.GenMan(c, &h, &buf); err != nil {
		return err
	}

	page, err := fixOptions(buf.Bytes())
	if err != nil {
		return fmt.Errorf("%s: %w", c.CommandPath(), err)
	}

	// The same name as in SEE ALSO, without the Markdown escapes of Use.
	name := strings.ReplaceAll(c.CommandPath(), " ", "-")
	name = strings.ReplaceAll(name, `\`, "") + "." + header.Section

	// Man pages are world-readable.
	return os.WriteFile(filepath.Join(dir, name), page, 0o644) //nolint:gosec // see above
}

// optionRe matches an option as cobra/doc writes it: the flag in bold on one
// line, its description on the next after a tab, which go-md2man no longer
// turns into a tagged paragraph.
var optionRe = regexp.MustCompile(`(?m)^(?:\.PP\n)?(\\fB-.*)\n\t`)

// fixOptions renders every option as a tagged paragraph (.TP): the flag,
// then its description indented below. The description starts with \& so
// that a leading "." or "'" is not read as a roff request.
//
// It fails when a line still starts with a tab outside an example (.EX):
// cobra/doc or go-md2man changed their output and the regex no longer
// matches, which would ship flat option lists without any other warning.
func fixOptions(page []byte) ([]byte, error) {
	page = optionRe.ReplaceAll(page, []byte(".TP\n$1\n\\&"))

	example := false
	for l := range strings.SplitSeq(string(page), "\n") {
		switch {
		case strings.HasPrefix(l, ".EX"):
			example = true
		case strings.HasPrefix(l, ".EE"):
			example = false
		case !example && strings.HasPrefix(l, "\t"):
			return nil, fmt.Errorf("option not rendered as .TP: %q", l)
		}
	}

	return page, nil
}

// escapeTree escapes the texts cobra/doc renders as Markdown, in every
// command; a flag inherited by several commands is escaped once.
func escapeTree(c *cobra.Command, seen map[*pflag.Flag]bool) {
	c.Use = escapeLine(c.Use)
	c.Short = escapeLine(c.Short)
	c.Long = escapeText(c.Long)

	escapeFlag := func(f *pflag.Flag) {
		if seen[f] {
			return
		}

		seen[f] = true
		f.Usage = escapeText(f.Usage)
		// cobra/doc quotes string defaults (%q), which would double the
		// backslashes.
		if f.Value.Type() != "string" {
			f.DefValue = escapeLine(f.DefValue)
		}
	}
	c.LocalFlags().VisitAll(escapeFlag)
	c.InheritedFlags().VisitAll(escapeFlag)

	for _, sub := range c.Commands() {
		escapeTree(sub, seen)
	}
}

// escapeText escapes a help text line by line. A run of indented lines (a
// command line, a table, an example) is kept verbatim in a code block, so
// that it is neither filled nor justified.
func escapeText(s string) string {
	var out []string

	lines := strings.Split(s, "\n")
	for i := 0; i < len(lines); {
		if !indented(lines[i]) {
			out = append(out, escapeLine(lines[i]))
			i++

			continue
		}

		j := i
		for j < len(lines) && (indented(lines[j]) || blankInside(lines, j)) {
			j++
		}

		// Blank lines around the fence: it must start a block of its own.
		out = append(out, "", "```")
		out = append(out, lines[i:j]...)
		out = append(out, "```", "")
		i = j
	}

	return strings.Join(out, "\n")
}

func indented(l string) bool {
	return strings.TrimSpace(l) != "" && (strings.HasPrefix(l, " ") || strings.HasPrefix(l, "\t"))
}

// blankInside reports whether lines[i] is an empty line between two indented
// lines, which belongs to the same code block.
func blankInside(lines []string, i int) bool {
	return strings.TrimSpace(lines[i]) == "" && i+1 < len(lines) && indented(lines[i+1])
}

// markdownInline lists the characters Markdown reads anywhere in a line.
var markdownInline = strings.NewReplacer(
	`\`, `\\`, "`", "\\`", `*`, `\*`, `_`, `\_`,
	`<`, `\<`, `>`, `\>`, `[`, `\[`, `]`, `\]`,
)

// escapeLine escapes one line of plain text for Markdown, including the
// characters that start a list, a heading or a quote.
func escapeLine(l string) string {
	l = markdownInline.Replace(l)

	trimmed := strings.TrimLeft(l, " ")
	if trimmed != "" && strings.ContainsRune("-+#", rune(trimmed[0])) {
		l = l[:len(l)-len(trimmed)] + `\` + trimmed
	}

	return l
}
